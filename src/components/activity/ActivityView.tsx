interface Props {
  viewAll: boolean;
  canGenerate: boolean;
  initial: { items: ActivityDTO[]; nextCursor: string | null };
  reports: Partial<Record<Period, TeamReportDTO>>;
  stats: Record<Period, MemberStats[]>;
}

const initialOf = (name: string) => name.slice(0, 1).toUpperCase();

export default function ActivityView({ viewAll, canGenerate, initial, reports: initialReports, stats }: Props) {
  const [period, setPeriod] = useState<Period>('week');

  return (
    <div className="space-y-6">
      <PageHeader
        title="Activity"
        subtitle={viewAll ? 'Everything that happens in your workspace, plus an AI read on how the team is doing.' : 'Everything you’ve done in this workspace.'}
        actions={
          <div className="flex rounded-2xl bg-surface-2 p-1">
            {(Object.keys(PERIOD_LABEL) as Period[]).map((p) => (
              <button key={p} onClick={() => setPeriod(p)} className={`rounded-xl px-3 py-1.5 text-xs font-semibold transition ${period === p ? 'bg-surface text-fg shadow-soft' : 'text-muted'}`}>
                {PERIOD_LABEL[p]}
              </button>
            ))}
          </div>
        }
      />
      {viewAll && <TeamReportCard period={period} canGenerate={canGenerate} initial={initialReports} />}
      <TeamTable rows={stats[period]} period={period} viewAll={viewAll} />
      <ActivityLog initial={initial} members={stats.month} viewAll={viewAll} />
    </div>
  );
}

// ---------- AI team report ----------

function TeamReportCard({ period, canGenerate, initial }: { period: Period; canGenerate: boolean; initial: Props['reports'] }) {
  const [reports, setReports] = useState(initial);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const current = reports[period];

  async function generate() {
    setBusy(true);
    setError('');
    try {
      const res = await api<{ report: TeamReportDTO }>('/api/ai/team-report', { body: { period, now: localNow() } });
      setReports((r) => ({ ...r, [period]: res.report }));
    } catch (err) {
      setError(errorText(err));
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className={`card overflow-hidden ${busy ? 'ai-shimmer' : ''}`}>
      <div className="flex flex-wrap items-center gap-4 border-b border-line p-6">
        <span className="icon-tile size-12 shrink-0">
          <Sparkles className="size-5" />
        </span>
        <div className="mr-auto min-w-0">
          <h2 className="text-base font-bold">AI team report · last {PERIOD_LABEL[period]}</h2>
          <p className="text-sm text-muted">
            {current ? (
              <>
                Generated by {current.createdBy} · <When value={current.createdAt} ago /> · {current.provider}
              </>
            ) : (
              'A per-person summary of the team’s work: highlights, risks and one coaching tip each.'
            )}
          </p>
        </div>
        {canGenerate && (
          <button className={current ? 'btn-ghost' : 'btn-primary'} onClick={generate} disabled={busy}>
            {busy ? <Loader2 className="size-4 animate-spin" /> : current ? <RefreshCw className="size-4" /> : <Sparkles className="size-4" />}
            {busy ? 'Analysing team…' : current ? 'Regenerate' : 'Generate report'}
          </button>
        )}
      </div>

      {error && (
        <div className="px-6 pt-5">
          <ErrorText>{error}</ErrorText>
        </div>
      )}

      {current ? (
        <div className="space-y-6 p-6">
          <div>
            <p className="text-xl font-bold leading-snug">{current.report.headline}</p>
            <p className="mt-2 max-w-4xl text-sm leading-relaxed text-fg/80">{current.report.overview}</p>
          </div>

          <div className="grid gap-4 md:grid-cols-2 2xl:grid-cols-3">
            {current.report.members.map((m) => {
              const r = RATING[m.rating] ?? RATING.steady;
              return (
                <article key={m.memberId} className="flex flex-col rounded-3xl bg-surface-2 p-5">
                  <div className="flex items-center gap-3">
                    <span className="grid size-10 place-items-center rounded-full bg-brand text-sm font-bold text-white">{initialOf(m.name)}</span>
                    <p className="mr-auto min-w-0 truncate font-bold">{m.name}</p>
                    <span className={`chip ${r.tone}`}>{r.label}</span>
                  </div>
                  <p className="mt-3 text-sm leading-relaxed text-fg/85">{m.summary}</p>
                  {(m.highlights.length > 0 || m.concerns.length > 0) && (
                    <ul className="mt-3 space-y-1.5 text-sm">
                      {m.highlights.map((h, i) => (
                        <li key={`h${i}`} className="flex gap-2">
                          <Check className="mt-0.5 size-4 shrink-0 text-success" /> {h}
                        </li>
                      ))}
                      {m.concerns.map((c, i) => (
                        <li key={`c${i}`} className="flex gap-2">
                          <AlertTriangle className="mt-0.5 size-4 shrink-0 text-amber-500" /> {c}
                        </li>
                      ))}
                    </ul>
                  )}
                  <p className="mt-auto flex gap-2 rounded-2xl bg-surface p-3 pt-3 text-sm [margin-top:1rem]">
                    <Lightbulb className="mt-0.5 size-4 shrink-0 text-brand-2" /> {m.suggestion}
                  </p>
                </article>
              );
            })}
          </div>

          {current.report.recommendations.length > 0 && (
            <div className="rounded-3xl bg-brand p-5 text-white">
              <p className="mb-2 text-sm font-bold">Recommended next steps for the team</p>
              <ol className="list-decimal space-y-1 pl-5 text-sm text-white/85">
                {current.report.recommendations.map((r, i) => (
                  <li key={i}>{r}</li>
                ))}
              </ol>
            </div>
          )}
        </div>
      ) : (
        !busy && (
          <p className="px-6 py-10 text-center text-sm text-muted">
            {canGenerate ? 'No report for this period yet. Generate one — it uses 1 AI action and is saved for everyone with access.' : 'No report for this period yet.'}
          </p>
        )
      )}
    </section>
  );
}

