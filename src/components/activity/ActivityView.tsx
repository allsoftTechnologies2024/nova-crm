function TeamTable({ rows, period, viewAll }: { rows: MemberStats[]; period: Period; viewAll: boolean }) {
  const sorted = [...rows].sort((a, b) => b.counts.total - a.counts.total);
  const cols: [string, (m: MemberStats) => React.ReactNode][] = [
    ['Leads added', (m) => m.counts.leadsCreated],
    ['Stage moves', (m) => m.counts.stageChanges],
    ['Won', (m) => (m.counts.won ? `${m.counts.won} · ${compactInr(m.wonValue)}` : 0)],
    ['Notes / calls', (m) => m.counts.notes + m.counts.calls + m.counts.emails],
    ['AI actions', (m) => m.counts.aiActions],
    ['Open leads', (m) => m.openLeads],
    ['Overdue', (m) => (m.overdueFollowUps ? <span className="font-bold text-rose-500">{m.overdueFollowUps}</span> : 0)],
  ];
  return (
    <section className="card overflow-hidden">
      <div className="flex items-center justify-between border-b border-line px-6 py-4">
        <h2 className="text-base font-bold">{viewAll ? 'Team at a glance' : 'Your numbers'}</h2>
        <span className="text-xs font-semibold text-muted">Last {PERIOD_LABEL[period]}</span>
      </div>
      <div className="scroll-thin overflow-x-auto">
        <table className="w-full min-w-[820px] text-sm">
          <thead className="text-left text-xs text-muted">
            <tr className="border-b border-line">
              <th className="px-6 py-3 font-semibold">Member</th>
              {cols.map(([h]) => (
                <th key={h} className="px-3 py-3 text-right font-semibold">
                  {h}
                </th>
              ))}
              <th className="px-6 py-3 text-right font-semibold">Last active</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-line">
            {sorted.map((m) => (
              <tr key={m.id} className={m.active ? '' : 'opacity-50'}>
                <td className="px-6 py-3">
                  <div className="flex items-center gap-3">
                    <span className="grid size-8 place-items-center rounded-full bg-surface-2 text-xs font-bold">{initialOf(m.name)}</span>
                    <div>
                      <p className="font-semibold">{m.name}</p>
                      <p className="text-xs text-muted">{ROLE_META[m.role].label}</p>
                    </div>
                  </div>
                </td>
                {cols.map(([h, get]) => (
                  <td key={h} className="px-3 py-3 text-right tabular-nums">
                    {get(m)}
                  </td>
                ))}
                <td className="px-6 py-3 text-right">{m.lastActive ? <When value={m.lastActive} ago /> : <span className="text-xs text-muted">Never</span>}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

