const RANGES = [
  { value: '1', label: 'Last 24 hours' },
  { value: '7', label: 'Last 7 days' },
  { value: '30', label: 'Last 30 days' },
  { value: '90', label: 'Last 90 days' },
  { value: '', label: 'All time' },
];

// Server render and hydration both use India time so the markup matches; after mount we switch to the
// viewer's own time zone (see useViewerTimeZone), which can regroup items across midnight.
const SERVER_TZ = 'Asia/Kolkata';
const dayKey = (d: Date, timeZone: string) => new Intl.DateTimeFormat('en-CA', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);

function dayLabel(iso: string, timeZone: string) {
  const d = new Date(iso);
  const now = new Date();
  const key = dayKey(d, timeZone);
  if (key === dayKey(now, timeZone)) return 'Today';
  if (key === dayKey(new Date(now.getTime() - 86_400_000), timeZone)) return 'Yesterday';
  const sameYear = key.slice(0, 4) === dayKey(now, timeZone).slice(0, 4);
  return d.toLocaleDateString('en-IN', { timeZone, weekday: 'long', day: 'numeric', month: 'short', year: sameYear ? undefined : 'numeric' });
}

function useViewerTimeZone() {
  const [timeZone, setTimeZone] = useState(SERVER_TZ);
  useEffect(() => setTimeZone(Intl.DateTimeFormat().resolvedOptions().timeZone || SERVER_TZ), []);
  return timeZone;
}

function ActivityLog({ initial, members, viewAll }: { initial: Props['initial']; members: MemberStats[]; viewAll: boolean }) {
  const [items, setItems] = useState(initial.items);
  const [cursor, setCursor] = useState(initial.nextCursor);
  const [filters, setFilters] = useState({ actor: '', category: '', days: '', q: '' });
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const first = useRef(true);

  const params = useMemo(() => {
    const sp = new URLSearchParams();
    Object.entries(filters).forEach(([k, v]) => v && sp.set(k, v));
    return sp;
  }, [filters]);

  async function load(more: boolean) {
    setLoading(true);
    setError('');
    try {
      const sp = new URLSearchParams(params);
      if (more && cursor) sp.set('before', cursor);
      const res = await api<{ items: ActivityDTO[]; nextCursor: string | null }>(`/api/activity?${sp}`);
      setItems((cur) => (more ? [...cur, ...res.items] : res.items));
      setCursor(res.nextCursor);
    } catch (err) {
      setError(errorText(err));
    } finally {
      setLoading(false);
    }
  }

  // Refetch when filters change (search is debounced).
  useEffect(() => {
    if (first.current) {
      first.current = false;
      return;
    }
    const t = setTimeout(() => load(false), filters.q ? 300 : 0);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [params]);

  // Leads deleted later shouldn't link to a 404.
  const deleted = useMemo(() => new Set(items.filter((i) => i.action === 'lead.deleted').map((i) => i.entity?.id)), [items]);

  const timeZone = useViewerTimeZone();
  const groups = useMemo(() => {
    const out: { day: string; rows: ActivityDTO[] }[] = [];
    for (const it of items) {
      const day = dayLabel(it.at, timeZone);
      if (out[out.length - 1]?.day === day) out[out.length - 1].rows.push(it);
      else out.push({ day, rows: [it] });
    }
    return out;
  }, [items, timeZone]);

  return (
    <section className="card overflow-hidden">
      <div className="flex flex-wrap items-center gap-2 border-b border-line px-6 py-4">
        <h2 className="mr-auto text-base font-bold">Activity log</h2>
        <div className="relative w-full sm:w-56">
          <Search className="pointer-events-none absolute left-3 top-1/2 size-4 -translate-y-1/2 text-muted" />
          <input className="input py-2 pl-9 text-xs" placeholder="Search activity…" value={filters.q} onChange={(e) => setFilters({ ...filters, q: e.target.value })} />
        </div>
        {viewAll && (
          <Select
            size="sm"
            className="w-40"
            aria-label="Filter by member"
            value={filters.actor}
            onChange={(actor) => setFilters({ ...filters, actor })}
            options={[{ value: '', label: 'Everyone' }, ...members.map((m) => ({ value: m.id, label: m.name })), { value: 'system', label: 'System' }]}
          />
        )}
        <Select
          size="sm"
          className="w-44"
          aria-label="Filter by type"
          value={filters.category}
          onChange={(category) => setFilters({ ...filters, category })}
          options={[{ value: '', label: 'All activity' }, ...(Object.keys(CATEGORY) as Category[]).map((c) => ({ value: c, label: CATEGORY[c].label }))]}
        />
        <Select size="sm" className="w-36" aria-label="Date range" value={filters.days} onChange={(days) => setFilters({ ...filters, days })} options={RANGES} />
        <a href={`/api/activity/export?${params}`} className="btn-ghost py-2 text-xs" download>
          <Download className="size-3.5" /> CSV
        </a>
      </div>

      {error && (
        <div className="px-6 pt-4">
          <ErrorText>{error}</ErrorText>
        </div>
      )}

      <div className={`px-6 py-2 transition ${loading && !cursor ? 'opacity-60' : ''}`}>
        {groups.length === 0 && !loading && <p className="py-12 text-center text-sm text-muted">No activity matches these filters.</p>}
        {groups.map((g) => (
          <div key={g.day}>
            <p className="sticky top-0 bg-surface py-3 text-xs font-bold uppercase tracking-wider text-muted">{g.day}</p>
            <ol className="relative mb-4 space-y-1 border-l border-line pl-6">
              {g.rows.map((a) => {
                const Icon = CATEGORY[a.category]?.icon ?? LayoutGrid;
                return (
                  <li key={a.id} className="relative flex items-start gap-3 rounded-2xl py-2 pr-2">
                    <span className={`absolute -left-[37px] top-2.5 grid size-6 place-items-center rounded-full ring-4 ring-surface ${a.category === 'ai' ? 'bg-brand-2 text-white' : 'bg-surface-2 text-muted'}`}>
                      <Icon className="size-3" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <p className="text-sm">
                        <b className="font-semibold">{a.actor.name}</b> <span className="text-fg/80">{lowerFirst(a.summary)}</span>
                        {a.meta?.viaSupport ? <span className="chip ml-2 bg-fg text-white ring-fg">via support</span> : null}
                      </p>
                      <p className="mt-0.5 flex flex-wrap items-center gap-x-2 text-xs text-muted">
                        <When value={a.at} />
                        {a.entity?.type === 'lead' && !deleted.has(a.entity.id) && (
                          <Link href={`/app/leads/${a.entity.id}`} className="font-semibold hover:text-brand">
                            Open lead →
                          </Link>
                        )}
                      </p>
                    </div>
                  </li>
                );
              })}
            </ol>
          </div>
        ))}
        {cursor && (
          <div className="pb-4 text-center">
            <button className="btn-ghost" onClick={() => load(true)} disabled={loading}>
              {loading ? <Loader2 className="size-4 animate-spin" /> : null} Load more
            </button>
          </div>
        )}
      </div>
    </section>
  );
}

// Summaries are written as sentences ("Moved X …"); after the actor's name they read better lowercased.
const lowerFirst = (s: string) => (/^[A-Z][a-z]/.test(s) ? s.charAt(0).toLowerCase() + s.slice(1) : s);
